#!/usr/bin/env php
<?php

declare(strict_types=1);

require_once __DIR__.'/depth/PhpAnalyzer.php';
require_once __DIR__.'/depth/SpecParser.php';
require_once __DIR__.'/depth/Inspector.php';

use Erp\Depth\Inspector;

function usage(): never
{
    fwrite(STDERR, "Usage: php tools/depth-check.php <module-id>|--all [--gate] [--run-tests] [--json] [--write-status] [--root=path] [--phpunit=script]\n");
    exit(2);
}

$options = ['gate' => false, 'run-tests' => false, 'json' => false, 'write-status' => false];
$selector = null;
$root = dirname(__DIR__);
$testCommand = null;
foreach (array_slice($argv, 1) as $argument) {
    $flag = substr($argument, 2);
    if (str_starts_with($argument, '--') && array_key_exists($flag, $options) && ! $options[$flag]) {
        $options[$flag] = true;
    } elseif (str_starts_with($argument, '--root=')) {
        $root = rtrim(substr($argument, 7), '/');
    } elseif (str_starts_with($argument, '--phpunit=')) {
        $testCommand = [PHP_BINARY, substr($argument, 10)];
    } elseif ($selector === null && ($argument === '--all' || preg_match('/^[a-z][a-z0-9-]*$/D', $argument) === 1)) {
        $selector = $argument;
    } else {
        usage();
    }
}
if ($selector === null || ($options['write-status'] && $selector !== '--all')) {
    usage();
}
// The gate executes module tests for every module whose static checks pass, so a completion claim is never accepted untested.
$runTests = $options['gate'] || $options['run-tests'];
try {
    $inspector = new Inspector($root, $testCommand);
    $reports = $selector === '--all' ? $inspector->inspectAll($runTests) : [$inspector->inspect($selector, $runTests)];
} catch (RuntimeException $e) {
    fwrite(STDERR, 'ERROR: '.$e->getMessage()."\n");
    exit(2);
}

$failures = [];
foreach ($reports as $report) {
    if ($report['status'] === 'done' && ! $report['pass']) {
        $failures[] = $report['id'].': marked done but does not pass the depth gate';
    } elseif ($report['status'] === 'partial' && $report['suggested_status'] === 'stub') {
        $failures[] = $report['id'].': marked partial but has no Laravel implementation (use stub)';
    }
}

$short = ['entity_cov' => 'entity', 'event_cov' => 'event', 'contract_cov' => 'contract', 'rule_cov' => 'rule', 'perm_cov' => 'perm', 'ui_cov' => 'ui', 'ai_cov' => 'ai'];
$percent = fn (float $value): string => rtrim(rtrim(number_format($value, 1, '.', ''), '0'), '.');
if ($options['write-status']) {
    $lines = [
        '# Module depth status',
        '',
        'Generated by `php tools/depth-check.php --all --gate --write-status`; do not edit by hand. CI regenerates it and fails on drift.',
        '',
        'A module passes only with score ≥ 80, every category ≥ 60 %, no anti-gaming findings and passing module tests (executed by `--gate` once the static checks pass). Weights: entity 20, event 15, contract 20, rule 20, perm 10, ui 10, ai 5. Coverage is measured by static heuristics described in `docs/decisions.md`.',
        '',
        '| Module | Status | Suggested | Score | '.implode(' | ', $short).' | Anti-gaming | Tests | Pass |',
        '|---|---|---|---:|'.str_repeat('---:|', count($short)).'---:|---|---|',
    ];
    foreach ($reports as $report) {
        $cells = array_map(fn (string $category) => $percent($report['categories'][$category]['percent']), array_keys($short));
        $lines[] = '| '.$report['id'].' | '.$report['status'].' | '.$report['suggested_status'].' | '.$percent($report['score']).' | '.implode(' | ', $cells).' | '.count($report['violations']).' | '.$report['tests']['status'].' | '.($report['pass'] ? 'yes' : 'no').' |';
    }
    foreach ($reports as $report) {
        $lines[] = '';
        $lines[] = '## '.$report['id'].' — '.$report['status'].', score '.$percent($report['score']).', '.($report['pass'] ? 'PASS' : 'FAIL');
        $lines[] = '';
        foreach ($report['categories'] as $category => $result) {
            $head = '- '.$category.' '.$percent($result['percent']).'% ('.$result['covered'].'/'.$result['total'].')';
            $lines[] = $result['missing'] === [] ? $head.': complete' : $head.':';
            foreach ($result['missing'] as $gap) {
                $lines[] = '  - '.str_replace('|', '\\|', $gap);
            }
        }
        $lines[] = '- anti-gaming: '.($report['violations'] === [] ? 'clean' : count($report['violations']).' finding(s)');
        foreach ($report['violations'] as $violation) {
            $lines[] = '  - '.$violation;
        }
        $lines[] = '- tests: '.$report['tests']['status'].' ('.$report['tests']['detail'].')';
    }
    if (file_put_contents($root.'/docs/depth-status.md', implode("\n", $lines)."\n") === false) {
        fwrite(STDERR, "ERROR: cannot write docs/depth-status.md\n");
        exit(2);
    }
}

if ($options['json']) {
    echo json_encode(['modules' => $reports, 'gate_failures' => $failures], JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR)."\n";
} else {
    foreach ($reports as $report) {
        $cells = array_map(fn (string $category, string $label) => $label.' '.$percent($report['categories'][$category]['percent']), array_keys($short), $short);
        echo $report['id'].' ['.$report['status'].' → '.$report['suggested_status'].'] score '.$percent($report['score']).' '.($report['pass'] ? 'PASS' : 'FAIL').' ('.implode(', ', $cells).'; anti-gaming '.count($report['violations']).'; tests '.$report['tests']['status'].")\n";
        if ($selector !== '--all') {
            foreach ($report['categories'] as $category => $result) {
                foreach ($result['missing'] as $gap) {
                    echo '  - '.$category.': '.$gap."\n";
                }
            }
            foreach ($report['violations'] as $violation) {
                echo '  - anti-gaming: '.$violation."\n";
            }
        }
    }
}

if ($options['gate'] && $failures !== []) {
    foreach ($failures as $failure) {
        fwrite(STDERR, 'GATE: '.$failure."\n");
    }
    exit(1);
}
