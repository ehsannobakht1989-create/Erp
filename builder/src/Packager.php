<?php

declare(strict_types=1);

namespace Builder;

use FilesystemIterator;
use RecursiveDirectoryIterator;
use RecursiveIteratorIterator;
use RuntimeException;
use ZipArchive;

/**
 * Transitional Phase 1 packager for the Laravel layout. Phase 3 replaces it with `php artisan erp:build`
 * (React bundle for the selected modules, INSTALL-FA.md, tick UI, clean `composer install --no-dev -o`).
 * The package contains the Laravel application, the selected modules without web sources or tests,
 * every module's src/Contracts, a generated config/erp-modules.php and vendor/ when it exists.
 */
final class Packager
{
    private const APP_PATHS = ['app', 'bootstrap/app.php', 'bootstrap/providers.php', 'config', 'database', 'lang', 'public', 'resources', 'routes', 'artisan', 'composer.json', 'composer.lock', '.env.example', '.htaccess'];

    private const MODULE_PATHS = ['module.json', 'README.md', 'Providers', 'src', 'database', 'routes', 'lang', 'workflows', 'forms', 'print'];

    private const WRITABLE_DIRECTORIES = ['bootstrap/cache', 'storage/app/private', 'storage/app/public', 'storage/framework/cache/data', 'storage/framework/sessions', 'storage/framework/views', 'storage/logs'];

    public function __construct(private readonly string $root, private readonly ?string $outputRoot = null, private readonly bool $includeVendor = true) {}

    /**
     * @param  array<string, mixed>  $resolved
     * @return array{zip:string, file_count:int, size_bytes:int, vendor:bool}
     */
    public function package(array $resolved): array
    {
        $slug = (string) ($resolved['factory']['slug'] ?? 'erp');
        if (preg_match('/^[a-z0-9][a-z0-9-]*$/D', $slug) !== 1) {
            throw new RuntimeException('Factory slug must be lowercase letters, digits and dashes.');
        }
        /** @var list<string> $modules */
        $modules = array_values($resolved['modules'] ?? []);
        $distDirectory = ($this->outputRoot ?? $this->root).'/dist';
        if (! is_dir($distDirectory) && ! mkdir($distDirectory, 0775, true)) {
            throw new RuntimeException("Cannot create $distDirectory");
        }
        $zipPath = $distDirectory."/$slug-1.0.0.zip";
        $zip = new ZipArchive;
        if ($zip->open($zipPath, ZipArchive::CREATE | ZipArchive::OVERWRITE) !== true) {
            throw new RuntimeException("Cannot create zip: $zipPath");
        }
        foreach (self::APP_PATHS as $path) {
            $this->add($zip, $path);
        }
        foreach (self::WRITABLE_DIRECTORIES as $directory) {
            $zip->addFromString($directory.'/.gitignore', "*\n!.gitignore\n");
        }
        $zip->addFromString('config/erp-modules.php', "<?php\n\ndeclare(strict_types=1);\n\n// Generated by the builder for profile '$slug'.\nreturn ".var_export(['enabled' => $modules], true).";\n");
        foreach (glob($this->root.'/modules/*/src/Contracts', GLOB_ONLYDIR) ?: [] as $contracts) {
            $this->add($zip, substr($contracts, strlen($this->root) + 1));
        }
        $statuses = [];
        foreach ($modules as $id) {
            foreach (self::MODULE_PATHS as $part) {
                $this->add($zip, "modules/$id/$part");
            }
            $manifest = json_decode((string) file_get_contents($this->root."/modules/$id/module.json"), true);
            $statuses[$id] = is_array($manifest) ? (string) ($manifest['status'] ?? 'stub') : 'invalid';
        }
        $vendor = $this->includeVendor && is_file($this->root.'/vendor/autoload.php');
        if ($vendor) {
            $this->add($zip, 'vendor');
        }
        $zip->addFromString('BUILD-REPORT.md', $this->report($slug, $resolved, $statuses, $vendor));
        $count = $zip->numFiles;
        if (! $zip->close()) {
            throw new RuntimeException("Cannot write zip: $zipPath");
        }

        return ['zip' => $zipPath, 'file_count' => $count, 'size_bytes' => (int) filesize($zipPath), 'vendor' => $vendor];
    }

    /**
     * @param  array<string, mixed>  $resolved
     * @param  array<string, string>  $statuses
     */
    private function report(string $slug, array $resolved, array $statuses, bool $vendor): string
    {
        $notDone = array_keys(array_filter($statuses, fn (string $status) => $status !== 'done'));
        $lines = [
            "# Build report: $slug",
            '',
            '- Modules ('.count($statuses).'): '.implode(', ', array_keys($statuses)),
            '- Auto-added dependencies: '.(empty($resolved['auto_added']) ? 'none' : (string) json_encode($resolved['auto_added'], JSON_UNESCAPED_SLASHES)),
            '- Resolver warnings: '.(empty($resolved['warnings']) ? 'none' : implode('; ', (array) $resolved['warnings'])),
            '- Python AI service needed: '.(! empty($resolved['python_needed']) ? 'yes' : 'no'),
            '- vendor/ included: '.($vendor ? 'yes' : 'NO — run `composer install --no-dev -o` before packaging; the package cannot boot without it'),
        ];
        if ($notDone !== []) {
            $lines[] = '- WARNING: '.count($notDone).' selected module(s) have not passed the depth gate: '.implode(', ', array_map(fn (string $id) => "$id ({$statuses[$id]})", $notDone));
        }
        $lines[] = '';
        $lines[] = 'Install: upload and extract, point the document root at public/ (or keep the root .htaccess), open /install, then add the cron line `* * * * * cd <path> && php artisan schedule:run`. See docs/deploy-cpanel-fa.md.';

        return implode("\n", $lines)."\n";
    }

    private function add(ZipArchive $zip, string $relative): void
    {
        $path = $this->root.'/'.$relative;
        if (is_file($path) && ! is_link($path)) {
            $zip->addFile($path, $relative);

            return;
        }
        if (! is_dir($path) || is_link($path)) {
            return;
        }
        $iterator = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($path, FilesystemIterator::SKIP_DOTS));
        foreach ($iterator as $file) {
            $name = $relative.'/'.str_replace('\\', '/', substr($file->getPathname(), strlen($path) + 1));
            if ($file->isFile() && ! $file->isLink() && $name !== 'config/erp-modules.php' && preg_match('#(^|/)(\.env|node_modules/|\.git/)#', $name) !== 1) {
                $zip->addFile($file->getPathname(), $name);
            }
        }
    }
}
